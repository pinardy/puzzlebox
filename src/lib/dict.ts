/** One flat lowercase set. The lists overlap freely — a Set sorts that out. */
export const DICT: ReadonlySet<string> = new Set<string>(
  [
    ...THREE,
    ...MID,
    ...LONG,
    ...COMMON,
    ...ANSWERS,
    ...GUESS4,
    ...CLUED3.map(([w]) => w),
    ...CLUED4.map(([w]) => w),
    ...CLUED5.map(([w]) => w)
  ]
    .map((w) => w.toLowerCase())
    // A stray accent or apostrophe would be unspellable on any of these
    // boards, so drop anything that isn't plain a–z.
    .filter((w) => /^[a-z]+$/.test(w))
);

export const WORDS: readonly string[] = [...DICT].sort();

export function isWord(w: string): boolean {
  return DICT.has(w.toLowerCase());
}

/** A word's letters as a 26-bit mask — the cheap way to ask "does this word
 *  stay inside that handful of letters?" over the whole dictionary. */
export function maskOf(word: string): number {
  let m = 0;
  for (let i = 0; i < word.length; i++) m |= 1 << (word.charCodeAt(i) - 97);
  return m;
}

export const bitCount = (m: number): number => {
  let n = 0;
  for (let x = m; x; x >>= 1) n += x & 1;
  return n;
};

/** Words of `minLen`+ letters that can be spelled from `mask` alone, and
 *  that use `required` at least once. Letters may repeat — that is the
 *  Spelling Bee rule, and the mask comparison gives it for free. */
export function wordsFrom(mask: number, required: string, minLen = 4): string[] {
  const need = 1 << (required.charCodeAt(0) - 97);
  const out: string[] = [];
  for (const w of WORDS) {
    if (w.length < minLen) continue;
    const m = maskOf(w);
    if ((m & need) === 0) continue;
    if ((m & ~mask) !== 0) continue;
    out.push(w);
  }
  return out;
}

/** Words whose letters are exactly seven distinct ones — the natural
 *  starting point for a Spelling Bee, since such a word is a pangram for
 *  its own letter set. */
export const PANGRAMS: readonly string[] = WORDS.filter(
  (w) => w.length >= 7 && bitCount(maskOf(w)) === 7
);

/** Words with no doubled letter, which is what Letter Boxed needs: a pair
 *  of identical letters can never sit on two different sides. */
export const NO_DOUBLES: readonly string[] = WORDS.filter((w) => {
  for (let i = 1; i < w.length; i++) if (w[i] === w[i - 1]) return false;
  return true;
});
